-- ---------------------------------------------------------------
-- Kolom periode pada tbl_laporan.
-- Ditambahkan dengan default SENSUS supaya seluruh laporan lama
-- bertanda SENSUS, lalu default diubah ke REVISIT untuk laporan baru.
-- ---------------------------------------------------------------
-- (Ditulis dengan pengecekan information_schema supaya jalan di MySQL
--  maupun MariaDB, dan aman bila skrip dijalankan ulang.)
SET @ada_kolom := (SELECT COUNT(*) FROM information_schema.COLUMNS
                   WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'tbl_laporan' AND COLUMN_NAME = 'periode');
SET @sql := IF(@ada_kolom = 0,
  'ALTER TABLE `tbl_laporan` ADD COLUMN `periode` enum(''SENSUS'',''REVISIT'') NOT NULL DEFAULT ''SENSUS'' AFTER `status`',
  'DO 0');
PREPARE stmt FROM @sql;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;

ALTER TABLE `tbl_laporan`
  MODIFY `periode` enum('SENSUS','REVISIT') NOT NULL DEFAULT 'REVISIT';

SET @ada_index := (SELECT COUNT(*) FROM information_schema.STATISTICS
                   WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'tbl_laporan' AND INDEX_NAME = 'idx_laporan_periode');
SET @sql := IF(@ada_index = 0,
  'ALTER TABLE `tbl_laporan` ADD INDEX `idx_laporan_periode` (`periode`)',
  'DO 0');
PREPARE stmt FROM @sql;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;

