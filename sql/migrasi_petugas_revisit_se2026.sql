SET NAMES utf8mb4;
SET FOREIGN_KEY_CHECKS = 0;
START TRANSACTION;

DROP TABLE IF EXISTS `tbl_alokasi_wilayah_revisit`;
DROP TABLE IF EXISTS `tbl_koseka_revisit_kecamatan`;
DROP TABLE IF EXISTS `tbl_koseka_revisit`;
DROP TABLE IF EXISTS `tbl_ppl_revisit`;
DROP TABLE IF EXISTS `tbl_pml_revisit`;

CREATE TABLE `tbl_pml_revisit` (
  `id` int(10) UNSIGNED NOT NULL AUTO_INCREMENT,
  `nama_pml` varchar(150) NOT NULL,
  `nomor_hp_pml` varchar(20) NOT NULL,
  `nomor_hp_sumber` varchar(100) DEFAULT NULL COMMENT 'Nomor sebagaimana tertulis di sumber data',
  `is_dummy` tinyint(1) NOT NULL DEFAULT 0,
  `keterangan` varchar(255) DEFAULT NULL,
  `updated_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `idx_pml_revisit_nama` (`nama_pml`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

CREATE TABLE `tbl_ppl_revisit` (
  `id` int(10) UNSIGNED NOT NULL AUTO_INCREMENT,
  `nama_ppl` varchar(150) NOT NULL,
  `nomor_hp_ppl` varchar(20) NOT NULL,
  `nomor_hp_sumber` varchar(100) DEFAULT NULL COMMENT 'Nomor sebagaimana tertulis di sumber data',
  `pml_id` int(10) UNSIGNED DEFAULT NULL,
  `is_dummy` tinyint(1) NOT NULL DEFAULT 0,
  `keterangan` varchar(255) DEFAULT NULL,
  `updated_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `idx_ppl_revisit_nama` (`nama_ppl`),
  KEY `fk_ppl_revisit_pml` (`pml_id`),
  CONSTRAINT `fk_ppl_revisit_pml` FOREIGN KEY (`pml_id`) REFERENCES `tbl_pml_revisit` (`id`) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

CREATE TABLE `tbl_koseka_revisit` (
  `id` int(10) UNSIGNED NOT NULL AUTO_INCREMENT,
  `nama_koseka` varchar(150) NOT NULL,
  `nomor_hp_koseka` varchar(20) NOT NULL,
  `is_dummy` tinyint(1) NOT NULL DEFAULT 0,
  `keterangan` varchar(255) DEFAULT NULL,
  `updated_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

CREATE TABLE `tbl_koseka_revisit_kecamatan` (
  `id` int(10) UNSIGNED NOT NULL AUTO_INCREMENT,
  `koseka_id` int(10) UNSIGNED NOT NULL,
  `kecamatan` varchar(100) NOT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_koseka_kecamatan` (`koseka_id`,`kecamatan`),
  KEY `idx_koseka_rev_kec` (`kecamatan`),
  CONSTRAINT `fk_koseka_rev_kec` FOREIGN KEY (`koseka_id`) REFERENCES `tbl_koseka_revisit` (`id`) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

CREATE TABLE `tbl_alokasi_wilayah_revisit` (
  `id` int(10) UNSIGNED NOT NULL AUTO_INCREMENT,
  `wilayah_id` int(10) UNSIGNED NOT NULL,
  `ppl_id` int(10) UNSIGNED NOT NULL,
  `jumlah_subsls` smallint(5) UNSIGNED NOT NULL DEFAULT 1,
  `daftar_idsubsls` text DEFAULT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_alokasi_revisit` (`wilayah_id`,`ppl_id`),
  KEY `fk_alokasi_revisit_ppl` (`ppl_id`),
  CONSTRAINT `fk_alokasi_revisit_ppl` FOREIGN KEY (`ppl_id`) REFERENCES `tbl_ppl_revisit` (`id`) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT `fk_alokasi_revisit_wilayah` FOREIGN KEY (`wilayah_id`) REFERENCES `tbl_wilayah` (`id`) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

