  KEY `idx_notif_laporan` (`laporan_id`),
  CONSTRAINT `fk_notif_laporan` FOREIGN KEY (`laporan_id`) REFERENCES `tbl_laporan` (`id`) ON DELETE CASCADE ON UPDATE CASCADE
